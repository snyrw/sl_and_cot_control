"""CoT length + surface-style stats for any set of generation rows (teacher data, student evals).

Also the cheap version of METR's surface habits (all-caps runs, JSON blocks, comma rate,
disclaimers), which Phase 3's filters target; reporting them per teacher makes asymmetric
filtering visible.
"""

from __future__ import annotations

import re
import statistics
from typing import Any

from cotsl.eval.common import length_stats
from cotsl.eval.cotcontrol import meta_regex

_CAPS_RUN = re.compile(r"(?:\b[A-Z]{2,}\b\W+){4,}")
_JSON_BLOCK = re.compile(r"```json|^\s*\{\s*\"", re.MULTILINE)
_DISCLAIMER = re.compile(r"THIS THOUGHT PROCESS WAS GENERATED BY AI|\bdisclaimer\b", re.IGNORECASE)


def style_features(text: str) -> dict[str, float]:
    words = text.split()
    letters = [c for c in text if c.isalpha()]
    return {
        "upper_letter_frac": (sum(c.isupper() for c in letters) / len(letters)) if letters else 0.0,
        "commas_per_100_words": (100 * text.count(",") / len(words)) if words else 0.0,
        "has_caps_run": float(bool(_CAPS_RUN.search(text))),
        "has_json_block": float(bool(_JSON_BLOCK.search(text))),
        "has_disclaimer": float(bool(_DISCLAIMER.search(text))),
        "meta_regex": float(meta_regex(text)),
        "non_ascii_frac": (sum(ord(c) > 127 for c in text) / len(text)) if text else 0.0,
    }


def summarize_rows(rows: list[dict[str, Any]], field: str = "analysis") -> dict[str, Any]:
    ok = [r for r in rows if not r.get("error")]
    feats = [style_features(r.get(field) or "") for r in ok]
    out: dict[str, Any] = {
        "n": len(ok),
        "n_errors": len(rows) - len(ok),
        "truncated_rate": (sum(r.get("stop_reason") == "length" for r in ok) / len(ok)) if ok else None,
        "empty_cot_rate": (sum(not r.get(field) for r in ok) / len(ok)) if ok else None,
        f"{field}_tokens": length_stats([r.get(f"n_{field}_tokens", 0) for r in ok]),
        "final_tokens": length_stats([r.get("n_final_tokens", 0) for r in ok if "n_final_tokens" in r]),
    }
    if feats:
        out["style_means"] = {k: statistics.fmean(f[k] for f in feats) for k in feats[0]}
    return out
